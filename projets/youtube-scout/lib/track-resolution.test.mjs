test("un featuring explicite ne reste pas simultanément primary", () => {
  const result = resolveTrack({
    title: "Nieuport Beach Ft. BEN PLG",
    channelTitle: "Absolem - Topic",
    description: `
Nieuport Beach Ft. BEN PLG · ABSOLEM · BEN plg
Main Artist: ABSOLEM
Main Artist: BEN plg
Auto-generated by YouTube.
`
  });

  assert.ok(
    result.secondaryCredits.some(
      ({ name, role }) =>
        name.toLocaleLowerCase() === "ben plg" &&
        role === "featuring"
    )
  );

  assert.ok(
    !result.issues.some(
      ({ type, candidates = [] }) =>
        type === "multiple_primary_candidates" &&
        candidates.some(
          ({ name }) =>
            name.toLocaleLowerCase() === "ben plg"
        )
    )
  );
});

