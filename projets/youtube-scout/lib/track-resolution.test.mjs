import test from "node:test";
import assert from "node:assert/strict";

import { resolveTrack } from "./track-resolution.mjs";

test("une chaîne Release - Topic ne devient jamais un artiste", () => {
  const result = resolveTrack({
    title: "BOYÉ - Skefre, Ismayyyel",
    channelTitle: "Release - Topic",
    description: `
BOYÉ - Skefre, Ismayyyel · Skefre
Auto-generated by YouTube.
`
  });

  assert.ok(
    !result.allArtistCandidates.some(
      ({ name }) => name === "Release"
    )
  );
});

test("la métadonnée Topic peut contester la frontière du titre", () => {
  const result = resolveTrack({
    title: "BOYÉ - Skefre, Ismayyyel",
    channelTitle: "Release - Topic",
    description: `
BOYÉ - Skefre, Ismayyyel · Skefre
Auto-generated by YouTube.
`
  });

  assert.ok(
    result.preferredArtists.some(
      ({ name }) => name === "Skefre"
    )
  );

  assert.equal(result.identityStatus, "unresolved");
});

test("un featuring reste secondaire", () => {
  const result = resolveTrack({
    title: "Nieuport Beach Ft. BEN PLG",
    channelTitle: "Absolem - Topic",
    description: `
Nieuport Beach Ft. BEN PLG · ABSOLEM

Main Artist: ABSOLEM
Featured Artist: BEN PLG
Auto-generated by YouTube.
`
  });

  assert.ok(
    result.preferredArtists.some(
      ({ name }) => name === "ABSOLEM"
    )
  );

  assert.ok(
    result.secondaryCredits.some(
      ({ name, role }) =>
        name === "BEN PLG" &&
        role === "featuring"
    )
  );
});

test("une graphie différente ne résout pas une identité canonique", () => {
  const result = resolveTrack({
    title: "Nightly Cares",
    channelTitle: "Mum - Topic",
    description: `
Nightly Cares · Múm
Auto-generated by YouTube.
`
  });

  assert.equal(result.identityStatus, "unresolved");
  assert.ok(result.preferredArtists.length >= 1);
});

test("plusieurs artistes documentés restent visibles", () => {
  const result = resolveTrack({
    title: "Pas lâcher",
    channelTitle: "1863 - Topic",
    description: `
Pas lâcher · 1863

Main Artist: 1863
Artist: Kosei
Artist: La Fève
Auto-generated by YouTube.
`
  });

  assert.ok(
    result.preferredArtists.some(
      ({ name }) => name === "1863"
    )
  );

  assert.ok(
    result.secondaryCredits.some(
      ({ name, role }) =>
        name === "Kosei" &&
        role === "credited"
    )
  );

  assert.ok(
    result.secondaryCredits.some(
      ({ name, role }) =>
        name === "La Fève" &&
        role === "credited"
    )
  );
});

test("un titre Topic contenant un tiret reste un titre et ne fabrique pas un artiste", () => {
  const result = resolveTrack({
    title: "BOYÉ - Skefre, Ismayyyel",
    channelTitle: "Release - Topic",
    description: `
BOYÉ - Skefre, Ismayyyel · Skefre
Auto-generated by YouTube.
`
  });

  assert.equal(
    result.title,
    "BOYÉ - Skefre, Ismayyyel"
  );

  assert.deepEqual(
    result.preferredArtists.map(({ name }) => name),
    ["Skefre"]
  );

  assert.ok(
    !result.allArtistCandidates.some(
      ({ name }) => name === "BOYÉ"
    )
  );
});

test("une collaboration documentée n'est pas signalée comme conflit", () => {
  const result = resolveTrack({
    title: "Comic sans MS",
    channelTitle: "Caballero & JeanJass - Topic",
    description: `
Comic sans MS · Caballero & JeanJass
Auto-generated by YouTube.
`
  });

  assert.ok(
    result.issues.some(
      ({ type, severity }) =>
        type === "documented_collaboration" &&
        severity === "info"
    )
  );

  assert.ok(
    !result.issues.some(
      ({ type }) =>
        type === "multiple_primary_candidates"
    )
  );
});

