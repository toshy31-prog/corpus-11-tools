import test from "node:test";
import assert from "node:assert/strict";

import {
  buildTrackSearchProjection
} from "./track-search-projection.mjs";

test("produit une requête exacte sans modifier la source", () => {
  const input = {
    title: "As We Begin",
    channelTitle: "Pye Corner Audio - Topic",
    description: `
As We Begin · Pye Corner Audio
Main Artist: Pye Corner Audio
Auto-generated by YouTube.
`
  };

  const before = JSON.stringify(input);

  const projection =
    buildTrackSearchProjection(input);

  assert.equal(
    JSON.stringify(input),
    before
  );

  assert.ok(
    projection.queries.some(
      (query) =>
        query.kind === "exact" &&
        query.artist === "Pye Corner Audio" &&
        query.title === "As We Begin"
    )
  );

  assert.equal(
    projection.policy.mutatesRaw,
    false
  );
});

test("génère une variante sans diacritiques sans déclarer un alias", () => {
  const projection =
    buildTrackSearchProjection({
      title: "Nightly Cares",
      channelTitle: "Mum - Topic",
      description: `
Nightly Cares · Múm
Auto-generated by YouTube.
`
    });

  assert.ok(
    projection.queries.some(
      ({ artist }) => artist === "Múm"
    )
  );

  assert.ok(
    projection.queries.some(
      ({ artist }) => artist === "Mum"
    )
  );

  assert.equal(
    projection.policy.normalizationsAreAliases,
    false
  );
});

