test("la version peut être ajoutée temporairement au titre de recherche", () => {
  const projection =
    buildTrackSearchProjection({
      title: "Freeze (Thomas Schumacher Remix)",
      channelTitle: "Huntemann - Topic",
      description: `
Freeze (Thomas Schumacher Remix) · Huntemann
Main Artist: Huntemann
Remixer: Thomas Schumacher
Auto-generated by YouTube.
`
    });

  assert.equal(
    projection.interpreted.title,
    "Freeze"
  );

  assert.ok(
    projection.queries.some(
      ({ title }) =>
        title ===
        "Freeze Thomas Schumacher Remix"
    )
  );
});

test("les candidats concurrents restent des recherches faibles et non des identités", () => {
  const projection =
    buildTrackSearchProjection({
      title: "Ignition Key (Original Mix)",
      channelTitle: "Kei Hayakawa - Topic",
      description: `
Ignition Key (Original Mix) · Ken Hayakawa
Artist: Ken Hayakawa
Auto-generated by YouTube.
`
    });

  assert.equal(
    projection.interpreted.identityStatus,
    "unresolved"
  );

  assert.ok(
    projection.queries.length > 0
  );

  assert.equal(
    projection.policy.identityResolved,
    false
  );
});

test("une absence de catalogue reste vide et ne devient jamais la chaîne null", () => {
  const projection =
    buildTrackSearchProjection({
      title: "Metal Works (Original Mix)",
      channelTitle: "POLI - Topic",
      description: `
Metal Works (Original Mix) · PØLI
Auto-generated by YouTube.
`
    });

  assert.equal(
    projection.interpreted.catalogueCode,
    null
  );

  assert.ok(
    projection.queries.every(
      ({ catalogueCode }) =>
        catalogueCode !== "null"
    )
  );

  assert.ok(
    !projection.queries.some(
      ({ transformations }) =>
        transformations.includes(
          "catalogue_constraint"
        )
    )
  );
});

test("un conteneur Release - Topic ne pollue pas les requêtes artiste", () => {
  const projection =
    buildTrackSearchProjection({
      title: "BOYÉ - Skefre, Ismayyyel",
      channelTitle: "Release - Topic",
      description: `
BOYÉ - Skefre, Ismayyyel · Skefre
Auto-generated by YouTube.
`
    });

  assert.ok(
    !projection.queries.some(
      ({ artist }) =>
        artist === "Release"
    )
  );

  assert.ok(
    projection.queries.some(
      ({ artist }) =>
        artist === "Skefre"
    )
  );
});

test("une position vinyle devient une variante de recherche sans modifier l'interprétation", () => {
  const projection =
    buildTrackSearchProjection({
      title: "B1. Pye Corner Audio - Island Of Ghosts [AF010]",
      channelTitle: "DMTR // NO Sleep",
      description: ""
    });

  assert.ok(
    projection.queries.some(
      ({ artist, transformations }) =>
        artist === "Pye Corner Audio" &&
        transformations.includes(
          "strip_track_position_prefix"
        )
    )
  );

  assert.ok(
    projection.queries.some(
      ({ artist }) =>
        artist === "B1. Pye Corner Audio"
    )
  );
});
