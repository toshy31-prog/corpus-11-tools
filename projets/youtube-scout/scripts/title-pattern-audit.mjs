import fs from "node:fs";
import path from "node:path";
import { parseTrackExpression } from "../lib/track-expression.mjs";

const input = process.argv[2];

if (!input) {
  console.error(
    "Usage: node scripts/title-pattern-audit.mjs /chemin/backup.json"
  );
  process.exit(2);
}

const absolute = path.resolve(input);
const backup = JSON.parse(fs.readFileSync(absolute, "utf8"));

if (!Array.isArray(backup.library)) {
  throw new Error("Le JSON ne contient pas de tableau library");
}

const counters = {
  total: 0,
  parsed: 0,
  partial: 0,
  unparsed: 0,

  separatorDash: 0,
  separatorUnicodeDash: 0,

  featuring: 0,
  jointAmpersand: 0,
  jointX: 0,
  versus: 0,

  remix: 0,
  edit: 0,
  originalMix: 0,

  squareBrackets: 0,
  parentheses: 0,

  officialNoise: 0,
  topicChannel: 0,
  autoGenerated: 0,

  multipleBoundaries: 0,
  lowConfidenceBoundary: 0
};

const buckets = {
  partial: [],
  multipleBoundaries: [],
  featuring: [],
  collaboration: [],
  remix: [],
  catalogue: [],
  topicWithoutBoundary: [],
  strange: []
};

function sample(bucket, item, parsed, max = 40) {
  if (buckets[bucket].length >= max) return;

  buckets[bucket].push({
    id: item.id,
    title: item.title,
    channelTitle: item.channelTitle,
    parsed
  });
}

for (const item of backup.library) {
  const title = String(item.title || "");
  const description = String(item.description || "");
  const channelTitle = String(item.channelTitle || "");

  counters.total++;

  if (/\s-\s/u.test(title)) counters.separatorDash++;
  if (/\s[–—−]\s/u.test(title)) counters.separatorUnicodeDash++;

  if (/\b(?:feat(?:uring)?\.?|ft\.?)\b/iu.test(title)) {
    counters.featuring++;
  }

  if (/\s&\s/u.test(title)) counters.jointAmpersand++;
  if (/\s(?:x|×)\s/iu.test(title)) counters.jointX++;
  if (/\bvs\.?\b/iu.test(title)) counters.versus++;

  if (/\bremix\b/iu.test(title)) counters.remix++;
  if (/\bedit\b/iu.test(title)) counters.edit++;
  if (/\boriginal mix\b/iu.test(title)) counters.originalMix++;

  if (/\[[^\]]+\]/u.test(title)) counters.squareBrackets++;
  if (/\([^)]*\)/u.test(title)) counters.parentheses++;

  if (
    /\b(?:official video|official music video|official audio|clip officiel|lyrics? video|visuali[sz]er)\b/iu.test(
      title
    )
  ) {
    counters.officialNoise++;
  }

  const isTopic = /\s-\sTopic$/iu.test(channelTitle);
  if (isTopic) counters.topicChannel++;

  const autoGenerated =
    /Auto-generated by YouTube\./iu.test(description);

  if (autoGenerated) counters.autoGenerated++;

  const parsed = parseTrackExpression(title);

  counters[parsed.status] =
    (counters[parsed.status] || 0) + 1;

  if (parsed.status === "partial") {
    sample("partial", item, parsed);

    if (isTopic) {
      sample("topicWithoutBoundary", item, parsed);
    }
  }

  if ((parsed.candidates || []).length > 1) {
    counters.multipleBoundaries++;
    sample("multipleBoundaries", item, parsed);
  }

  if (
    parsed.status === "parsed" &&
    (parsed.confidence?.boundary || 0) < 0.6
  ) {
    counters.lowConfidenceBoundary++;
  }

  if (
    (parsed.artists || []).some(
      (artist) => artist.role === "featuring"
    )
  ) {
    sample("featuring", item, parsed);
  }

  if (
    (parsed.artists || []).some(
      (artist) =>
        artist.role === "joint" ||
        artist.role === "versus"
    )
  ) {
    sample("collaboration", item, parsed);
  }

  if (parsed.version?.kind === "remix") {
    sample("remix", item, parsed);
  }

  if (parsed.catalogueCode) {
    sample("catalogue", item, parsed);
  }

  /*
   * Cas potentiellement intéressants :
   * beaucoup de séparateurs mais aucune lecture vraiment sûre.
   */
  const dashCount =
    (title.match(/\s(?:-|–|—|−)\s/gu) || []).length;

  if (
    dashCount >= 3 ||
    title.length > 140 ||
    /(?:\bA[1-9]\b|\bB[1-9]\b)/u.test(title)
  ) {
    sample("strange", item, parsed);
  }
}

const pct = (n) =>
  counters.total
    ? Number(((n / counters.total) * 100).toFixed(2))
    : 0;

const summary = {
  source: absolute,
  total: counters.total,

  parsing: {
    parsed: counters.parsed,
    parsedPct: pct(counters.parsed),
    partial: counters.partial,
    partialPct: pct(counters.partial),
    unparsed: counters.unparsed,
    unparsedPct: pct(counters.unparsed)
  },

  syntax: counters,

  samples: buckets
};

const outputDir = path.resolve("validation-0.14");
fs.mkdirSync(outputDir, { recursive: true });

const jsonPath = path.join(
  outputDir,
  "title-pattern-audit.json"
);

fs.writeFileSync(
  jsonPath,
  JSON.stringify(summary, null, 2) + "\n"
);

